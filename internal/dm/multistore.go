// Multistore follows docker-magento's README ("Multi-storefront /
// multi-domain setup", option 1): an nginx map from host name to run code,
// mounted into the app container from compose.override.yaml.

const (
	StoreMapFile   = "store.map.conf"
	StoreMapTarget = "/etc/nginx/conf.d/store.map.conf"
	StoreMapVolume = "./" + StoreMapFile + ":" + StoreMapTarget + ":cached"
	NginxSample    = "src/nginx.conf.sample"
)

// Site is one store view as the multistore setup sees it.
type Site struct {
	StoreCode   string
	WebsiteCode string
	Default     bool // default store view of the default website
	Host        string
}

// RunMapping is one host → run code line in the map.
type RunMapping struct {
	Host, Code, Type string // Type: store or website
}

// Mappings works out MAGE_RUN_CODE / MAGE_RUN_TYPE per host. A host used
// by one store view maps to that store; a host shared by the store views
// of one website maps to the website (Magento picks its default store, and
// store codes in URLs pick the others). The default store's host needs no
// line. A host shared across websites cannot be mapped: those stores need
// their own domains, which is reported as a problem.
func Mappings(sites []Site) ([]RunMapping, []string) {
	byHost := map[string][]Site{}
	var hosts []string
	defHost := ""
	for _, s := range sites {
		if s.Host == "" {
			continue
		}
		if _, ok := byHost[s.Host]; !ok {
			hosts = append(hosts, s.Host)
		}
		byHost[s.Host] = append(byHost[s.Host], s)
		if s.Default {
			defHost = s.Host
		}
	}
	sort.Strings(hosts)
	var out []RunMapping
	var problems []string
	for _, h := range hosts {
		ss := byHost[h]
		if h == defHost {
			// Another website on the default host is unreachable.
			defWeb := websiteOf(ss, true)
			for _, s := range ss {
				if s.WebsiteCode != defWeb {
					problems = append(problems, fmt.Sprintf("store %s (website %s) shares %s with the default website — give it its own domain", s.StoreCode, s.WebsiteCode, h))
				}
			}
			continue
		}
		websites := map[string]bool{}
		for _, s := range ss {
			websites[s.WebsiteCode] = true
		}
		switch {
		case len(ss) == 1:
			out = append(out, RunMapping{Host: h, Code: ss[0].StoreCode, Type: "store"})
		case len(websites) == 1:
			out = append(out, RunMapping{Host: h, Code: ss[0].WebsiteCode, Type: "website"})
		default:
			var codes []string
			for _, s := range ss {
				codes = append(codes, s.StoreCode)
			}
			problems = append(problems, fmt.Sprintf("%s is used by stores of different websites (%s) — give each website its own domain", h, strings.Join(codes, ", ")))
		}
	}
	return out, problems
}

func websiteOf(ss []Site, def bool) string {
	for _, s := range ss {
		if s.Default == def {
			return s.WebsiteCode
		}
	}
	return ""
}

// StoreMapConf renders store.map.conf. $host has no port, unlike $http_host.
func StoreMapConf(ms []RunMapping) string {
	var b strings.Builder
	b.WriteString("# Generated by lazymage: host name → Magento run code (docker-magento multistore).\n")
	b.WriteString("# Mounted into the app container by compose.override.yaml; src/nginx.conf.sample\n")
	b.WriteString("# passes both values to PHP as MAGE_RUN_CODE / MAGE_RUN_TYPE.\n\n")
	b.WriteString("map $host $MAGE_RUN_CODE {\n    default \"\";\n")
	for _, m := range ms {
		fmt.Fprintf(&b, "    %s %s;\n", m.Host, m.Code)
	}
	b.WriteString("}\n\nmap $host $MAGE_RUN_TYPE {\n    default store;\n")
	for _, m := range ms {
		if m.Type != "store" {
			fmt.Fprintf(&b, "    %s %s;\n", m.Host, m.Type)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

const runParamsMarker = "# lazymage: multistore run code"

var phpLocationRe = regexp.MustCompile(`(?s)(location ~ \^/\(index\|get\|static\|errors/report\|errors/404\|errors/503\|health_check\)\\\.php\$ \{.*?include\s+fastcgi_params;)`)

// HasRunParams reports whether nginx.conf.sample passes the run code to PHP.
func HasRunParams(sample string) bool {
	return strings.Contains(sample, "fastcgi_param  MAGE_RUN_CODE") || strings.Contains(sample, "fastcgi_param MAGE_RUN_CODE") || strings.Contains(sample, runParamsMarker)
}

// AddRunParams adds MAGE_RUN_CODE / MAGE_RUN_TYPE to the PHP location of
// Magento's nginx.conf.sample. Magento's sample does not pass them, so the
// map alone changes nothing. The result is unchanged if they are there.
func AddRunParams(sample string) (string, error) {
	if HasRunParams(sample) {
		return sample, nil
	}
	loc := phpLocationRe.FindStringIndex(sample)
	if loc == nil {
		return "", fmt.Errorf("could not find the PHP location block (index|get|static…\\.php) in %s", NginxSample)
	}
	insert := "\n    " + runParamsMarker + "\n    fastcgi_param  MAGE_RUN_CODE $MAGE_RUN_CODE;\n    fastcgi_param  MAGE_RUN_TYPE $MAGE_RUN_TYPE;"
	return sample[:loc[1]] + insert + sample[loc[1]:], nil
}

// HostsHas reports whether an /etc/hosts-format file maps host.
func HostsHas(hostsFile, host string) bool {
	f, err := os.Open(hostsFile)
	if err != nil {
		return false
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		fs := strings.Fields(line)
		for _, n := range fs[min(1, len(fs)):] {
			if strings.EqualFold(n, host) {
				return true
			}
		}
	}
	return false
}

// Resolves reports whether host resolves on this machine.
func Resolves(host string) bool {
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()
	addrs, err := net.DefaultResolver.LookupHost(ctx, host)
	return err == nil && len(addrs) > 0
}

// LocalTLS is where the local nginx listens for HTTPS (tests change it).
var LocalTLS = "127.0.0.1:443"

// CertHosts asks the local nginx (127.0.0.1:443) for the certificate it
// serves to host and returns the names it covers.
func CertHosts(host string) ([]string, error) {
	d := &net.Dialer{Timeout: 3 * time.Second}
	conn, err := tls.DialWithDialer(d, "tcp", LocalTLS, &tls.Config{ServerName: host, InsecureSkipVerify: true}) //nolint:gosec // reading the names only
	if err != nil {
		return nil, err
	}
	defer conn.Close()
	cs := conn.ConnectionState().PeerCertificates
	if len(cs) == 0 {
		return nil, fmt.Errorf("no certificate")
	}
	return cs[0].DNSNames, nil
}

// CertCovers reports whether names (from a certificate) cover host.
func CertCovers(names []string, host string) bool {
	for _, n := range names {
		if strings.EqualFold(n, host) {
			return true
		}
		if rest, ok := strings.CutPrefix(n, "*."); ok {
			if _, after, ok := strings.Cut(host, "."); ok && strings.EqualFold(after, rest) {
				return true
			}
		}
	}
	return false
}

// IsWSL reports whether lazymage runs under Windows Subsystem for Linux,
// where the browser reads Windows' hosts file, not /etc/hosts.
func IsWSL() bool {
	b, err := os.ReadFile("/proc/version")
	return err == nil && strings.Contains(strings.ToLower(string(b)), "microsoft")
}

